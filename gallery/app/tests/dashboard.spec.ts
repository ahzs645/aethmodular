test('weather, calibration and map snapshots replay saved auxiliary files without requesting them again', async ({ page }) => {
  for (const kind of ['wxtimeline', 'calcross', 'map']) {
    await open(page, tile(kind), { sites: 'Addis Ababa' })
    await expect(page.locator('.dash-tile svg').first()).toBeVisible({ timeout: 20000 })
    await display(page)
    const event = page.waitForEvent('download'); await page.getByRole('button', { name: 'Download snapshot' }).click()
    const file = path.join(output, `${kind}-snapshot.json`); await (await event).saveAs(file)
    const bundle = JSON.parse(readFileSync(file, 'utf8'))
    if (kind === 'wxtimeline') expect(bundle.snapshot.files['weather/daily/ETAD.json']).toBeTruthy()
    else if (kind === 'calcross') expect(bundle.snapshot.calibration.runs.runs.length).toBeGreaterThan(0)
    else expect(bundle.snapshot.files['world.geojson']).toBeTruthy()
    const requests: string[] = []
    const watcher = (r: { url(): string }) => { if (/\/data\/(weather|calibration|world|aeronet|spartan_map|improve_map)/.test(r.url())) requests.push(r.url()) }
    page.on('request', watcher)
    await page.getByLabel('Open dashboard snapshot file').setInputFiles(file)
    await expect(page.locator('.snapshot-banner')).toBeVisible()
    await expect(page.locator('.dash-tile svg').first()).toBeVisible()
    await page.waitForTimeout(400)
    expect(requests).toEqual([])
    page.off('request', watcher)
    await screenshot(page, `snapshot-${kind}`)
  }
})

