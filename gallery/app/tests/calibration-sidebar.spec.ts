test('shared CV updates search plots while the exported run keeps its actual site-grouped protocol', async ({ page }) => {
  await ready(page)
  await panel(page).getByRole('combobox', { name: 'Cohort', exact: true }).click()
  await page.getByRole('option', { name: 'Ethiopia-shaped smoke', exact: true }).click()
  const count = () => page.locator('#slope-trap .control').filter({ hasText: /^\d+ configurations$/ }).innerText()
  const before = Number.parseInt(await count(), 10)
  const curve = await page.locator('#cv-curve .chart-wrap path').evaluateAll(els => els.map(el => el.getAttribute('d')))
  await panel(page).getByRole('combobox', { name: 'Cross-validation protocol', exact: true }).click()
  await page.getByRole('option', { name: 'Interleaved CV (10-fold, every 10th filter)', exact: true }).click()
  await expect(page.locator('#spec-curve [data-shared-calibration-filter]')).toContainText('Cross-validation: Interleaved CV')
  await expect.poll(async () => Number.parseInt(await count(), 10)).toBeLessThan(before)
  await expect(page.locator('#cv-curve')).toContainText('site-grouped CV')
  expect(await page.locator('#cv-curve .chart-wrap path').evaluateAll(els => els.map(el => el.getAttribute('d')))).toEqual(curve)
  expect(new URL(page.url()).searchParams.get('calibration.cv')).toBe('app')
  await page.reload()
  await expect(panel(page).getByRole('combobox', { name: 'Cohort', exact: true })).toContainText('Ethiopia-shaped smoke')
  await expect(panel(page).getByRole('combobox', { name: 'Cross-validation protocol', exact: true })).toContainText('Interleaved CV (10-fold')
  await expect(page.locator('#cv-curve')).toContainText('300 calibration filters')
})

test('the VIP cohort is matched across searches and a missing protocol is reported without substituting results', async ({ page }) => {
  await ready(page)
  await panel(page).getByRole('combobox', { name: 'Cohort', exact: true }).click()
  await page.getByRole('option', { name: 'Spectral analogs (VIP-weighted distance)', exact: true }).click()
  await expect(page.locator('#spec-curve [data-shared-calibration-filter]')).toContainText('Spectral analogs')
  await expect(page.locator('#spec-curve .control').filter({ hasText: /^\d[\d,]* of [\d,]+ shown/ })).not.toHaveText(/^0 of /)
  await panel(page).getByRole('combobox', { name: 'Cross-validation protocol', exact: true }).click()
  await page.getByRole('option', { name: 'Interleaved CV, first-minimum rule', exact: true }).click()
  await expect(page.locator('#spec-curve')).toContainText('No saved configuration matches these filters')
  await expect(page.locator('#cv-curve')).toContainText('site-grouped CV')
})

